# Initialization
def initialize_robustness_vectors(data_size):
    C = np.zeros(data_size)
    R_plus = np.zeros(data_size)
    R_minus = np.zeros(data_size)
    return C, R_plus, R_minus

def create_random_subset(data_size, min_size=10, max_size=None):
    max_size = max_size or data_size  # Default max_size to data_size
    subset = set()
    while len(subset) < min_size:  # Ensure minimum size
        for i in range(data_size):
            if random.random() < 0.5:
                subset.add(i)
        if len(subset) > max_size:  # Ensure maximum size
            subset = set(random.sample(subset, max_size))
    return subset


# Add Gaussian noise to the dataset
def add_noise(data, L, sigma):
    noisy_data = []
    for _ in range(L):
        noise = np.clip(np.random.normal(0, sigma, data.shape), -3*sigma, 3*sigma)
        noisy_data.append(data + noise)
    return noisy_data


def train_model(train_data, train_labels, input_dim):
    """
    Train a deeper and more complex neural network model.

    Args:
    - train_data: Preprocessed training data.
    - train_labels: Training labels.
    - input_dim: Number of input features.

    Returns:
    - Trained Keras model.
    """
    model = Sequential([
        Input(shape=(input_dim,)),  # Input layer

        # Layer 1: Dense + BatchNorm + Dropout
        Dense(128, activation='relu', kernel_regularizer=l2(0.01)),
        BatchNormalization(),
        Dropout(0.3),

        # Layer 2: Dense + BatchNorm + Dropout
        Dense(64, activation='relu', kernel_regularizer=l2(0.01)),
        BatchNormalization(),
        Dropout(0.2),

        # Layer 3: Dense + BatchNorm
        Dense(32, activation='relu', kernel_regularizer=l2(0.01)),
        BatchNormalization(),

        # Output Layer
        Dense(1, activation='sigmoid')  # Binary classification
    ])

    model.compile(optimizer=Adam(learning_rate=0.001),
                  loss='binary_crossentropy',
                  metrics=['accuracy'])

    # Train the model
    model.fit(train_data, train_labels, epochs=20, batch_size=64, verbose=1)
    return model



def compute_robustness(model, X_test, y_test, L, sigma):
    """
    Compute robustness score for a model based on noisy variants of test data.

    Args:
    - model: Trained model for prediction.
    - X_test: Test dataset (clean samples).
    - y_test: True labels for the test dataset.
    - L: Number of noisy variants to generate.
    - sigma: Variance of Gaussian noise.

    Returns:
    - Robustness score as a float.
    """
    num_samples = X_test.shape[0]
    total_differences = 0

    # Generate noisy variants using the add_noise function
    noisy_variants = add_noise(X_test, L, sigma)

    for X_noisy in noisy_variants:
        # Get predictions for clean and noisy data
        predictions_clean = model.predict(X_test, verbose=0).round()
        predictions_noisy = model.predict(X_noisy, verbose=0).round()

        # Count the number of changed predictions for each sample
        differences = np.sum(predictions_clean != predictions_noisy)
        total_differences += differences

    # Normalize by the total number of comparisons
    robustness_score = total_differences / (L * num_samples)

    return robustness_score

def assign_robustness_scores(X_train, y_train, X_test, y_test):
    # Initialize robustness-related vectors
    C, R_plus, R_minus = initialize_robustness_vectors(len(X_train))

    # Preprocess data
    input_dim = X_train.shape[1]

    # Initialize a 2D array to store robustness scores for each subset
    R_accumulated = np.zeros((K, len(X_train)))  # K subsets x len(X_train)

    # Loop over K subsets
    for k in range(K):
        print(f"Processing subset {k + 1} of {K}...")  # Debugging output

        # Create random subset D_k
        subset_indices = list(create_random_subset(len(X_train)))
        excluded_indices = set(range(len(X_train))) - set(subset_indices)
        print(f"Included: {subset_indices[:10]}, Excluded: {list(excluded_indices)[:10]}")

        # Debugging subset indices
        # print(f"Subset indices D_i: {list(subset_indices)}")
        # print(f"Excluded indices D_o: {list(set(range(len(X_train))) - set(subset_indices))}")

        if not subset_indices:  # Ensure subset is non-empty
            print(f"Subset {k + 1} is empty, skipping...")
            continue

        D_k = X_train[subset_indices]
        D_k_labels = y_train[subset_indices]

        # Train model M_k
        model = train_model(D_k, D_k_labels, input_dim)

        # Compute robustness R_k
        R_k = compute_robustness(model, X_test, y_test, L, sigma)

        # Accumulate robustness scores for each sample
        for i in range(len(X_train)):
            if i in subset_indices:
               # print(f"Updating R_plus for sample {i}")
                R_plus[i] += R_k
                C[i] += 1  # Count usage of sample in subsets
            elif i in excluded_indices:
               # print(f"Updating R_minus for sample {i}")
                R_minus[i] += R_k




        # Compute and store robustness scores for this subset
        for i in range(len(X_train)):
            C_in = C[i]  # Subsets containing the sample
            C_out = k + 1 - C[i]  # Subsets processed so far NOT containing the sample

            # Avoid division by zero
            if C_in > 0:
                R_in = R_plus[i] / C_in
            else:
                R_in = 0

            if C_out > 0:
                R_out = R_minus[i] / C_out
            else:
                R_out = 0

            # Compute final score for this subset and store in 2D array
            R_accumulated[k, i] = R_out - R_in

       # Debugging
       # print(f"Subset {k + 1}: R_k = {R_k:.4f}")
       # print(f"Current C: {C}")
       # print(f"Current R_plus: {R_plus}")
       # print(f"Current R_minus: {R_minus}")

    print("Accumulated Robustness Scores (Raw):")
    print(R_accumulated)
    R_flattened = R_accumulated.flatten()  # Flatten to 1D array

    return R_accumulated, R_flattened  # Return both raw and flattened scores

