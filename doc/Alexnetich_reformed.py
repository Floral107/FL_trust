# Function to plot images with their robustness scores and save the figure
def plot_and_save_images(images, scores, title, filename):
    fig, axes = plt.subplots(10, 10, figsize=(20, 20))  # 10x10 grid for 100 images
    fig.suptitle(title, fontsize=16)
    for i, ax in enumerate(axes.flatten()):
        ax.imshow(images[i])
        ax.axis('off')
        ax.set_title(f"Score: {scores[i]:.3f}")
    plt.tight_layout()
    plt.savefig(filename)
    plt.close(fig)  # Close the figure to free memory

