from tensorflow.keras.optimizers import Adam
from tensorflow.keras.layers import Dense, Input
from tensorflow.keras.models import Model

def create_random_subset(data, inclusion_prob=0.5):
    """
    Creates a random subset of data with each element having a 50% chance of being included.
    """
    subset = [item for item in data if random.random() < inclusion_prob]
    return subset

def train_model_on_subset(subset_data, epochs=1, batch_size=4):
    """
    Trains a model on USE embeddings from a given subset of data.
    """
    # Prepare the data for training
    texts = [text for text, _ in subset_data]
    labels = np.array([label for _, label in subset_data])

    # Preprocess texts into embeddings
    embeddings = preprocess_text(texts)

    # Build the model using USE as the embedding layer
    inputs = Input(shape=(512,), dtype=tf.float32)  # USE embeddings are 512-dimensional
    x = Dense(128, activation='relu')(inputs)
    x = Dense(64, activation='relu')(x)
    outputs = Dense(2, activation='softmax')(x)
    model = Model(inputs=inputs, outputs=outputs)

    # Compile the model with Adam optimizer
    model.compile(optimizer=Adam(learning_rate=2e-5), loss="sparse_categorical_crossentropy", metrics=["accuracy"])

    # Train the model on the subset
    model.fit(embeddings, labels, epochs=epochs, batch_size=batch_size)

    return model

import numpy as np

def compute_robustness_score(model, all_texts, subset_texts, L=100, batch_size=16):
    """
    Computes robustness scores for each sample in the full dataset,
    distinguishing between in-sample and out-of-sample cases.

    Args:
    - model: Trained model to evaluate.
    - all_texts: List of all original text samples in the dataset.
    - subset_texts: List of texts included in the current training subset.
    - batch_size: Number of samples to process in each batch.

    Returns:
    - R_in: Array of robustness scores for samples in the subset (in-sample).
    - R_out: Array of robustness scores for samples not in the subset (out-of-sample).
    """
    # Embed all original texts
    embeddings_clean = preprocess_text(all_texts)

    # Get predictions for clean embeddings
    predictions_clean = model.predict(embeddings_clean, batch_size=batch_size)
    predictions_clean = np.argmax(predictions_clean, axis=1)
    print("Predictions for clean texts (first 10 samples):", predictions_clean[:10])

    # Generate noisy texts and embed them
    noisy_texts = [[add_noise(text) for _ in range(L)] for text in all_texts]
    flattened_noisy_texts = [noisy_text for noisy_versions in noisy_texts for noisy_text in noisy_versions]
    embeddings_noisy = preprocess_text(flattened_noisy_texts)

    # Get predictions for noisy embeddings
    predictions_noisy = model.predict(embeddings_noisy, batch_size=batch_size)
    predictions_noisy = np.argmax(predictions_noisy, axis=1)

    # Reshape noisy predictions to (num_samples, num_noisy_versions)
    num_noisy_versions = len(noisy_texts[0])
    predictions_noisy = predictions_noisy.reshape(len(all_texts), num_noisy_versions)

    print("Predictions for noisy texts (reshaped):", predictions_noisy[:5])  # Debugging output

    # Identify in-sample and out-of-sample indexes
    in_sample_indexes = [i for i, text in enumerate(all_texts) if text in subset_texts]
    out_sample_indexes = [i for i, text in enumerate(all_texts) if text not in subset_texts]

    # Initialize variables to accumulate robustness scores
    R_in_total = 0
    R_out_total = 0
    in_count = 0
    out_count = 0

    # Calculate robustness for each sample
    for i in range(len(all_texts)):
        # Robustness calculation: 1 if any noisy prediction differs from clean, 0 otherwise
        robustness_score = np.sum(predictions_noisy[i] != predictions_clean[i]) / L

        if i in in_sample_indexes:
            R_in_total += robustness_score
            in_count += 1
        else:
            R_out_total += robustness_score
            out_count += 1

    # Calculate average robustness scores
    R_in = R_in_total / in_count if in_count > 0 else 0
    R_out = R_out_total / out_count if out_count > 0 else 0

    return R_in, R_out

