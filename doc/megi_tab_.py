def display_robust_samples(X, y, robustness_scores, K, n):
    """
    Display the most and least robust samples from the dataset in a table,
    filtering out consecutive identical robustness scores.

    Args:
    - X: Original features dataset (DataFrame or array).
    - y: Labels dataset (array or list).
    - robustness_scores: Flattened array of robustness scores (length K * len(X)).
    - K: Number of subsets used to calculate robustness scores.
    - n: Number of samples to display for most and least robust.

    Returns:
    - Two DataFrames: Most robust and least robust samples.
    """
    # Reshape robustness scores to (K, len(X))
    robustness_scores = robustness_scores.reshape(K, len(X))

    # Create a DataFrame with original data, labels, and robustness scores for each subset
    data = pd.DataFrame(X)
    data['label'] = y
    for k in range(K):
        data[f'robustness_score_subset_{k}'] = robustness_scores[k]

    # Melt the DataFrame to have a single 'robustness_score' column
    data_melted = pd.melt(data,
                         id_vars=['label'] + list(data.columns[:X.shape[1]]),  # Original features and label
                         value_vars=[f'robustness_score_subset_{k}' for k in range(K)],
                         var_name='subset',
                         value_name='robustness_score')

    # Sort by robustness score
    data_melted['robustness_score'] = data_melted['robustness_score'].astype(np.float32)  # Change data type

    most_robust = data_melted.sort_values(by='robustness_score', ascending=False)
    least_robust = data_melted.sort_values(by='robustness_score', ascending=True)

    # Filter out consecutive identical scores for most robust
    most_robust_filtered = most_robust[
        most_robust['robustness_score'].ne(most_robust['robustness_score'].shift())
    ].head(n)

    # Filter out consecutive identical scores for least robust
    least_robust_filtered = least_robust[
        least_robust['robustness_score'].ne(least_robust['robustness_score'].shift())
    ].head(n)

    print(f"\nTop {n} Most Robust Samples (Filtered):")
    display(most_robust_filtered)

    print(f"\nTop {n} Least Robust Samples (Filtered):")
    display(least_robust_filtered)

    return most_robust_filtered, least_robust_filtered


