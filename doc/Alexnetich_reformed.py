def generate_random_subset(x_train, y_train, subset_ratio=0.5):
    """
    Generates a random subset of the training data.

    Parameters:
    - x_train: Training data (features).
    - y_train: Training labels.
    - subset_ratio: Fraction of the original data to include in the subset (default 0.5).
    Later changed to 0.025 so we can have smaller subset of data so the discrapenices in data are visible, due to smaller subset of data.

    Returns:
    - subset_x: Subset of the training data.
    - subset_y: Corresponding labels for the subset.
    - used_indices: Indices of the samples included in the subset.
    """
    num_samples = len(x_train)
    subset_size = int(num_samples * subset_ratio)

    used_indices = random.sample(range(num_samples), subset_size)  # Randomly sample indices
    subset_x = x_train[used_indices]
    subset_y = y_train[used_indices]

    return subset_x, subset_y, used_indices

def calculate_robustness_score(model, x_test, sigma, L):
    D_size = len(x_test)  # Size of test data

    # Predict for the entire test set at once
    predictions_clean = np.argmax(model.predict(x_test), axis=1)  # Clean predictions for all samples

    robustness_sum = 0
    for l in range(L):

        # Generate a noisy version of the test data on-the-fly
        noisy_test = x_test + np.random.normal(0, sigma, x_test.shape)  # Add Gaussian noise
        noisy_test = np.clip(noisy_test, 0., 1.)  # Clip to valid range (0, 1)


        # Predict for all noisy samples at once
        predictions_noisy = np.argmax(model.predict(noisy_test), axis=1)  # Noisy predictions for all samples

        # Compare predictions and count mismatches
        mismatches = np.sum(predictions_clean != predictions_noisy)
        robustness_sum += mismatches

    # Normalize by L and the dataset size
    robustness_score = robustness_sum / (L * D_size)

    return robustness_score

# Main robustness evaluation function
def compute_robustness(x_train, y_train, x_test, y_test, K=100, L=100, sigma=1, threshold=1):
    print("Starting compute_robustness function...")

    # Dynamically set the file name based on the script name, or use a default if __file__ is undefined
    try:
        base_filename = os.path.splitext(os.path.basename(__file__))[0]  # Gets the filename without extension
    except NameError:
        base_filename = "robustness_scores"  # Default name if running in interactive environment
    save_path = f"{base_filename}.npy"  # Constructs the .npy filename


    # Arrays to store the counts and robustness scores
    C = np.zeros(len(x_train))  # Count how many times each sample is used
    R_plus = np.zeros(len(x_train))  # Sum of robustness scores when sample is included
    R_minus = np.zeros(len(x_train))  # Sum of robustness scores when sample is excluded

    # Perturb the test dataset with Gaussian noise
    # noisy_test = [add_gaussian_noise(x_test, sigma) for _ in range(L)]

    for k in range(K):
        print(f"Training model {k + 1} of {K}")
        # Generate random subset of training data
        subset_x, subset_y, used_indices = generate_random_subset(x_train, y_train)

        print(f"Generated subset with {len(subset_x)} samples.")

        # Train the model on the random subset
        model = build_simple_model()
        model.fit(subset_x, subset_y, epochs=1, batch_size=64, verbose=1)

        # Calculate robustness score based on the new function
        robustness_score = calculate_robustness_score(model, x_test, sigma, L)

        # Update R+ and R- arrays based on the training subset
        for i in range(len(x_train)):
            if i in used_indices:
                R_plus[i] += robustness_score
                C[i] += 1  # Increment the usage counter
            else:
                R_minus[i] += robustness_score

    # Calculate final robustness scores for each sample
    print("Finalizing robustness scores...")
    epsilon = 1e-6  # Small constant to avoid division by zero
    R = np.zeros(len(x_train))
    for i in range(len(x_train)):
        if C[i] >= threshold and (K - C[i]) >= threshold:
            R[i] = (R_minus[i] / (K - C[i] + epsilon)) - (R_plus[i] / (C[i] + epsilon))
        else:
            R[i] = np.nan  # Set to NaN if not enough samples are used

    # Filter out NaN values before saving
    valid_scores = R[~np.isnan(R)]
    np.save(save_path, valid_scores)
    print(f"Non-NaN robustness scores saved to {save_path}")
    return R

# Test for the compute_robustness function
R = compute_robustness(x_train, y_train, x_test, y_test)
